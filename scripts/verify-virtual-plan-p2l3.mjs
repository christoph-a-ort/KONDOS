import { register } from "node:module";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
register(pathToFileURL(join(root, "scripts/ts-resolve-hook.mjs")).href);
const read = (file) => readFileSync(join(root, file), "utf8");
const assert = (value, label) => { if (!value) throw new Error(label); };
const journal = read("src/ui/virtualPlanJournal.ts");
const panel = read("src/ui/VirtualPlanJournalPanel.tsx");
const api = read("src/ui/virtualPlanJournalApi.ts");
const rust = read("src-tauri/src/commands/execution_binding.rs");
assert(journal.includes("createVirtualPlanJournal") && journal.includes("simulateJournalRecovery"), "journal simulation model");
assert(journal.includes("\"completed\"") && journal.includes("JOURNAL_COMPLETED_LABEL") && journal.includes("Abgeschlossen"), "FV2-01 completed status");
assert(journal.includes("completeExecutedJournal") && journal.includes("plannedOperationsReallyExecuted"), "FV2-01 completion proof");
assert(journal.includes("inferCompletedFromLegacyHints"), "FV2-01 no legacy auto-complete");
assert(journal.includes("ReadonlyArray<VirtualDryRunOperation>"), "immutable operation basis");
assert(journal.includes("reverse()"), "reverse recovery order");
assert(journal.includes("journalForBoundWrite") && journal.includes("parsePersistedJournal"), "persist helpers");
assert(!/invoke\(|fs\.|rename\(|copy\(|remove_file|create_dir/.test(journal), "no real filesystem operation");
assert(api.includes("inspectBoundExecution") && api.includes("startBoundExecution"), "bound inspect and start");
assert(api.includes("progressBoundExecution") && api.includes("prepareBoundRelease") && api.includes("releaseBoundExecution"), "bound progress and release");
assert(!api.includes("save_execution_journal") && !api.includes("load_execution_journal"), "unbound journal commands unused");
assert(panel.includes("Nur Simulation") && panel.includes("Simulation vorbereiten"), "clear simulation UI");
assert(panel.includes("Wiederherstellung simulieren"), "recovery UI");
assert(panel.includes("Freigabe vorbereiten") && panel.includes("Reservierung freigeben"), "safe release UI");
assert(panel.includes("startBoundExecution") && panel.includes("progressBoundExecution"), "UI uses bound persist");
assert(panel.includes("shouldAutoResumeSimulation"), "no automatic resume");
const reservation = read("src/ui/virtualPlanReservationAdmin.ts");
assert(panel.includes("reservationBindingLabel"), "journal panel reuses shared binding labels");
assert(reservation.includes("Unklarer Zustand") && reservation.includes("Beschädigte Daten"), "fail-closed UI states");
assert(panel.includes("Planrevision") && panel.includes("Journalrevision"), "distinct revision labels");
assert(panel.includes("journalStatusLabel"), "FV2-01 journal status label in simulation panel");
assert(reservation.includes("return \"Freigegeben\""), "FV2-01a released binding label");
assert(!reservation.includes("Abgeschlossen und freigegeben"), "FV2-01a old released label removed");
assert(panel.includes("Simulation abgeschlossen:"), "FV2-01a simulatedComplete counter");
assert(!panel.includes("Abgeschlossen:"), "FV2-01a bare Abgeschlossen counter removed");
assert(!panel.includes(">Ausführen<"), "no execute UI");
assert(rust.includes("inspect_bound_execution") && rust.includes("start_bound_execution"), "bound commands exist");
assert(rust.includes("inspect_scan_root_loads_reserved_journal_after_restart"), "restart load test");
assert(rust.includes("inspect_scan_root_progress_conflict_and_release"), "progress and release tests");
assert(rust.includes("inspect_scan_root_blocks_foreign_corrupt_and_inconsistent"), "blocked state tests");
const journalRs = read("src-tauri/src/commands/execution_journal.rs");
assert(journalRs.includes("save_unbound_at") && journalRs.includes("load_unbound_at"), "unbound journal commands are gated");
assert(journalRs.includes("unbound_save_cannot_bypass_binding"), "unbound save bypass test");
const { runVirtualPlanJournalCheck } = await import(
  pathToFileURL(join(root, "src/ui/virtualPlanJournalCheck.ts")).href,
);
runVirtualPlanJournalCheck();
console.log("virtual plan p2l3 checks passed");
