// P2-L.2: pure dry-run only; no executable filesystem operations.
import { register } from "node:module";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
register(pathToFileURL(join(root, "scripts/ts-resolve-hook.mjs")).href);
const read = (file) => readFileSync(join(root, file), "utf8");
const assert = (value, label) => { if (!value) throw new Error(label); };
const model = read("src/ui/virtualPlanDryRun.ts");
const panel = read("src/ui/VirtualPlanDryRunPanel.tsx");
const check = read("src/ui/virtualPlanEditorCheck.ts");
const css = read("src/App.css");
assert(model.includes("buildVirtualPlanDryRun"), "pure dry-run builder");
assert(model.includes('"createVirtualFolder"') && model.includes('"moveFile"') && model.includes('"renameFile"'), "virtual operation types");
assert(model.includes('plan.status !== "virtuallyApproved"'), "approval required");
assert(model.includes("targets.has"), "duplicate target check");
assert(model.includes("invalidName"), "Windows path check");
assert(!/invoke\(|fs\.|rename\(|copy\(|remove_file|mkdir/.test(model), "no filesystem operation API");
assert(panel.includes("Ausführung simulieren (Dry-Run)"), "dry-run UI");
assert(panel.includes("Zielordner anlegen") && panel.includes("Datei verschieben") && panel.includes("Datei umbenennen"), "German operation labels");
assert(panel.includes("Vor Ausführung erneut prüfen"), "German execution check label");
assert(panel.includes("Dies ist ausschließlich eine Simulation"), "simulation safety explanation");
assert(panel.includes("operation, index") && panel.includes("[{index + 1}]"), "visible deterministic operation order");
assert(!panel.includes(">Ausführen<"), "no execute UI");
assert(css.includes(".plan-dry-run-operations") && css.includes("grid-template-columns: repeat(auto-fit"), "responsive operation grid");
assert(!/\.plan-editor \{[^}]*overflow-y: auto/s.test(css), "plan editor has no nested vertical scroll");
assert(check.includes("current approved plan produces restricted dry run"), "approved plan test");
assert(check.includes("unapproved plan blocks dry run"), "unapproved block test");
assert(check.includes("stale plan blocks dry run"), "stale block test");
console.log("virtual plan p2l2 checks passed");
