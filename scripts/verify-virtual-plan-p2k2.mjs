import { register } from "node:module";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
register(pathToFileURL(join(root, "scripts/ts-resolve-hook.mjs")).href);
const read = (file) => readFileSync(join(root, file), "utf8");
const assert = (value, label) => { if (!value) throw new Error(label); };
const model = read("src/ui/virtualPlan.ts");
const check = read("src/ui/virtualPlanCheck.ts");
const api = read("src/ui/virtualPlanApi.ts");
const rust = read("src-tauri/src/commands/virtual_plan.rs");
const productionRust = rust.split("\n#[cfg(test)]\nmod tests")[0];
const app = read("src/App.tsx");
assert(model.includes("SnapshotBinding") && model.includes("ObservedObjectRef"), "model contracts");
assert(model.includes("identityUnavailable") && model.includes("snapshotFingerprint"), "identity safety");
assert(model.includes("parseVirtualPlan") && model.includes("canWriteVirtualDraft"), "validation");
assert(!model.includes("invoke(") && !model.includes("fs."), "pure model");
assert(api.includes("save_virtual_plan_draft"), "api");
assert(rust.includes("blocked") && rust.includes("expected_revision"), "backend lock/revision");
assert(rust.includes("discard_virtual_plan_draft"), "explicit discard only");
assert(productionRust.includes("app_data_dir") && productionRust.includes("virtual-plans"), "drafts stay in app data");
assert(!productionRust.includes("std::fs::copy") && !productionRust.includes("scan_result"), "no user fs action");
assert(check.includes("corrupt blocked") && check.includes("unknown version blocked"), "checks");
assert(!app.includes("virtualPlan"), "no planning UI in K.2");
const { runVirtualPlanCheck } = await import(pathToFileURL(join(root, "src/ui/virtualPlanCheck.ts")).href);
runVirtualPlanCheck();
console.log("virtual plan p2k2 checks passed");
