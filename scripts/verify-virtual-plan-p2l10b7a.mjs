import { register } from "node:module";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
register(pathToFileURL(join(root, "scripts/ts-resolve-hook.mjs")).href);
const read = (file) => readFileSync(join(root, file), "utf8");
const assert = (value, label) => { if (!value) throw new Error(label); };
const dialog = read("src/ui/NameSuggestDialog.tsx");
const form = read("src/ui/nameSuggestForm.ts");
const helper = read("src/ui/treeWorkbenchNameSuggest.ts");
assert(form.includes("parseNameSuggestDateInput") && form.includes("commitCalendarDateInput"), "typed and calendar dates share one parser");
assert(form.includes("shiftCalendarMonth") && form.includes("shiftCalendarYear"), "month and year navigation are modeled without selecting a day");
assert(form.includes("documentDateFieldIso") && form.includes("void args.fileName"), "filename dates are not used as the document date");
assert(form.includes("keepManualOverrides") && form.includes("nextAutoSuggestedFileName"), "manual fields and filenames are protected");
assert(helper.includes("parseUserDocumentDate") && helper.includes("formatIsoDate"), "existing date helpers remain");
assert(dialog.includes("type=\"text\"") && dialog.includes("placeholder=\"TT.MM.JJJJ\""), "German dates are typed in a text field");
assert(dialog.includes("type=\"date\"") && dialog.includes("name-suggest-date-picker"), "calendar remains a native date picker");
assert(dialog.includes("commitNameSuggestDateInput") && dialog.includes("commitCalendarDateInput"), "dialog commits dates through the shared helpers");
assert(dialog.includes("keepManualOverrides") && dialog.includes("nextAutoSuggestedFileName"), "KI cache cannot reset typed fields or a touched name");
assert(dialog.includes("rememberSender") && dialog.includes("shouldPersistSenderMapping"), "learned senders still save only after apply");
assert(dialog.includes("setRememberSender(false)"), "learn checkbox still starts unchecked");
assert(!dialog.includes("function handleDateChange"), "the old date wipe-on-invalid handler is gone");
const { runNameSuggestFormCheck } = await import(pathToFileURL(join(root, "src/ui/nameSuggestFormCheck.ts")).href);
runNameSuggestFormCheck();
